/* Shared by the navigator and the launch intro, which reveals the app only
   once every face is in — the navigator draws nothing until then. */
const APP_FONTS = {
  Nunito: Nunito_400Regular,
  // Only the bold face is loaded — the greeting is the sole place it's used.
  Caveat: Caveat_700Bold,
  NotoSerifSC: NotoSerifSC_400Regular,
  NotoSerifTC: NotoSerifTC_400Regular,
  // No 700 CJK face is loaded: its one use (PronunciationCheck) takes the
  // script's SemiBold through `hanziFont`, and dropping SC + TC Bold saved
  // 11MB. CJK has no synthesisable bold, so a new heavy use needs a face.

  // Reading Library / Story Reader faces. RN selects a weight by picking a
  // different family, so each one is registered separately — see the
  // `fontFamily` block in tailwind.config.js for the class names these back.
  NunitoSemiBold: Nunito_600SemiBold,
  // Example-sentence translations, set in italic.
  NunitoSemiBoldItalic: Nunito_600SemiBold_Italic,
  NunitoBold: Nunito_700Bold,
  // The Challenges screen's headings. Its spec asks for ExtraBold on titles
  // and Black nowhere — 900 is heavy enough that everything important stops
  // looking important.
  NunitoExtraBold: Nunito_800ExtraBold,
  NunitoBlack: Nunito_900Black,
  // The dictionary's editorial headings ("Dictionary", "Recent", "Explore")
  // and its one italic aside. A real bold, because a synthesised one does not
  // exist on native.
  // Noto *Sans* TC — the writing guide sets its Chinese UI text (part labels,
  // radical examples) in a sans to sit with Nunito, where the reader and
  // dictionary use the serif. A different typeface, so registered separately.
  // Bold only: nothing set Regular or Medium, which were 7MB together.
  NotoSansTCBold: NotoSansTC_700Bold,

  NotoSerifTCMedium: NotoSerifTC_500Medium,
  NotoSerifTCSemiBold: NotoSerifTC_600SemiBold,
  // The simplified counterparts, for surfaces that follow `settings.script`
  // rather than always rendering traditional — see `hanziFont` in lib/hanzi.ts.
  // Medium is the story reader's prose weight, mirroring NotoSerifTCMedium.
  NotoSerifSCMedium: NotoSerifSC_500Medium,
  NotoSerifSCSemiBold: NotoSerifSC_600SemiBold,
  CaveatMedium: Caveat_500Medium,
  /*
   * The Dashboard's handwritten learner name. Kalam rather than the Caveat
   * above: Caveat is a connected, slanted script, where the reference's name
   * is an upright marker hand with even stroke weight — at 33pt over a gold
   * brush stroke the difference is the whole character of the greeting.
   */
  KalamBold: Kalam_700Bold,

  // Dictionary faces. Nunito *Sans*, not the rounded Nunito the rest of the app
  // uses — a separate typeface, registered per weight for the same reason as
  // everything above.
}

function RootNavigator() {
  const { ready, onboardingComplete, wordBank, settings } = useApp()

  /*
   * Prepares the Dictionary in the background once the app has settled, so the
   * first tap on its tab is not the moment its search index and lists get
   * built (that was a visible stall on a phone).
   */
  const prewarmed = useRef(false)
  useEffect(() => {
    if (!ready || prewarmed.current) return
    prewarmed.current = true
    let timer: ReturnType<typeof setTimeout> | undefined
    const task = runAfterInteractions(() => {
      timer = setTimeout(() => {
        prefetchArt()
        prewarmDictionary(wordBank, settings.hskLevel, todayISO(), warmLookup)
      }, 3500)
    })
    return () => {
      task.cancel()
      if (timer) clearTimeout(timer)
    }
  }, [ready, wordBank, settings.hskLevel])
  /*
   * Held alongside `ready` rather than awaited separately: reading the stored
   * session is an AsyncStorage read, exactly like the rest of hydration, so it
   * costs nothing to wait for and spares the app a frame of signed-out UI
   * before the session lands. Nothing here touches the network — the splash
   * screen must never depend on a request.
   */
  const { ready: authReady } = useAuth()
  const pathname = usePathname()
  const [fontsLoaded] = useFonts(APP_FONTS)

  // One-time audio session setup. Without it, iOS mutes every effect whenever
  // the ring/silent switch is on.
  useEffect(() => {
    configureAudioSession()
  }, [])

  /*
   * The recurring ad-free offer. It lives up here rather than on a screen for
   * the same reason the tour overlay does: it has to outlive whichever screen
   * the learner happens to be on. It does nothing at all once the subscription
   * is active, and nothing during onboarding, a lesson or a review — see the
   * hook.
   */
  useSubscribePrompt()

  const appReady = ready && fontsLoaded && authReady

  useEffect(() => {
    if (appReady) SplashScreen.hideAsync().catch(() => {})
  }, [appReady])

  /*
   * The navigator mounts once and then stays mounted. It used to be swapped out
   * for `null` whenever `ready` dropped (signing in switches to the account's
   * own data) and for a `<Redirect>` whenever onboarding was unfinished. On
   * Android, Google's redirect also arrives as a deep link to /auth/callback
   * at that moment, and every remount re-applied it, which re-triggered the
   * redirect: an endless render loop ("Maximum update depth exceeded"). Now a
   * plain cover hides the screen during the switch, and the redirect is a
   * one-off navigation.
   */
  const navigatorMounted = useRef(false)
  const navReady = Boolean(useRootNavigationState()?.key)

  /* `/auth/*` is exempt: an emailed confirmation or reset link can arrive
     mid-onboarding, and redirecting it away would drop the code it carries.
     Those screens send the learner on to '/' themselves when they're done. */
  const needsOnboarding =
    appReady && !onboardingComplete && pathname !== '/onboarding' && !pathname.startsWith('/auth/')

  useEffect(() => {
    if (needsOnboarding && navReady) router.replace('/onboarding')
  }, [needsOnboarding, navReady, pathname])

  /* Before the first mount there is nothing to remount, so a fresh install
     still goes straight to onboarding without drawing Home underneath. */
  if (!navigatorMounted.current) {
    if (!appReady) return null
    if (needsOnboarding) return <Redirect href="/onboarding" />
    navigatorMounted.current = true
  }
  const covered = !appReady || needsOnboarding

  return (
    <>
      <StatusBar style="auto" />
      {/* Pages fade up into place (iOS honours the 450ms; Android uses its own
          fade-up timing). The Ad-free popup rises from the bottom like a sheet. */}
      <Stack screenOptions={{ headerShown: false, animation: 'fade_from_bottom', animationDuration: 450 }}>
        <Stack.Screen name="subscribe" options={{ animation: 'slide_from_bottom', gestureDirection: 'vertical' }} />
      </Stack>
      {/*
        Above the navigator, so Shifu stays put across every screen the tour
        walks through instead of being unmounted at each move. It draws nothing
        when no tour is running.
      */}
      {covered ? (
        /* Account switch or onboarding redirect in progress: show nothing, on the same white as the splash. */
        <View pointerEvents="auto" style={[StyleSheet.absoluteFill, { backgroundColor: launchColors.page }]} />
      ) : (
        <>
          {/* The (0, 0) both overlays draw from; targets are measured against it. */}
          <TourOrigin />
          <TourOverlay />
          {/* The first-visit guides on Learn, Dictionary and Settings. */}
          <ScreenTourOverlay />
          {/*
            Level-ups and achievements, noticed on whichever screen they happen on.
            It holds its queue while the learner is mid-task — see the component.
          */}
          <ProgressionCelebration />
        </>
      )}
    </>
  )
}

/*
 * The launch intro, beside the navigator rather than inside it: the router
 * remounts the root navigator's subtree when it first gets a navigator to
 * show, which restarted the intro the moment the app finished loading. Out
 * here it plays once, takes over from the native splash (plain white, like
 * its first frame) as soon as it can draw, and covers the app while it
 * hydrates. RootNavigator's hide on `appReady` stays as the fallback.
 */
function LaunchLayer() {
  const { ready } = useApp()
  const { ready: authReady } = useAuth()
  // The same set as RootNavigator's; expo-font loads each face once.
  const [fontsLoaded] = useFonts(APP_FONTS)
  const [done, setDone] = useState(false)
  const hideSplash = useCallback(() => {
    SplashScreen.hideAsync().catch(() => {})
  }, [])
  const end = useCallback(() => setDone(true), [])
  if (done) return null
  return (
    <LaunchIntro
      appReady={ready && authReady && fontsLoaded}
      onVisible={hideSplash}
      onDone={end}
    />
  )
}

export default function RootLayout() {
  return (
    <GestureHandlerRootView style={{ flex: 1 }}>
      <SafeAreaProvider>
        {/*
          Auth wraps the app store, not the other way round: the sync layer
          lives inside AppContext and needs to know which user it is syncing
          for, so the session has to be readable from in there.
        */}
        <AuthProvider>
          <AppProvider>
            {/*
              Ads sit inside the app store because that is where `isAdFree`
              lives, and the ad layer derives from it rather than keeping a
              premium flag of its own — one entitlement, one answer. Inside the
              navigator's parent rather than around it so a banner is always
              below the navigation tree it belongs to.
            */}
            <AdsProvider>
              <RootNavigator />
            </AdsProvider>
            {/* Last, so it covers everything until its wave has passed. */}
            <LaunchLayer />
          </AppProvider>
        </AuthProvider>
      </SafeAreaProvider>
    </GestureHandlerRootView>
  )
}
