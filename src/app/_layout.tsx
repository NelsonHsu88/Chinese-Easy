/*
 * The seven CJK faces come from src/assets/fonts, not from their packages.
 *
 * They are the same Noto faces, subset to the 13,349 characters this app can
 * actually display — a full Noto CJK face carries ~31,000 glyphs, and the rest
 * was 58MB of weight nobody's phone would ever draw. Generated by
 * scripts/subsetFonts.py from the corpus that scripts/buildCharacterCorpus.mjs
 * derives from the dictionary, the stroke data, the stories and every source
 * file. That script re-opens each output, reads its cmap, and fails rather than
 * emit a face that lost a character the original could draw — so these are
 * verified, not merely generated. Re-run both after the word bank or the
 * stories change.
 *
 * The Latin families below are still imported from their packages: 3.3MB
 * together, where subsetting would risk a missing glyph for no real saving.
 */
