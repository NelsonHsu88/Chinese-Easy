/*
 * Renders the launch intro (scene.mjs) to video.
 *
 *   node scripts/launch/render.mjs                     full render → src/assets/video/launch-intro.mp4
 *   node scripts/launch/render.mjs --sheet 0.4,1.2,…   contact sheet of those instants → <out>/sheet.png
 *   node scripts/launch/render.mjs --frames <dir>      keep the PNG frames there
 *
 * Frames are rasterised by sharp (librsvg) across worker threads and encoded
 * by ffmpeg as H.264 (yuv420p, level 4.2 so mid-range Android decoders take it
 * at 60fps). Pure white stays exactly white through the YUV round trip, which
 * is why the intro's page is #FFFFFF: the video's edges vanish into the screen.
 * Also writes src/components/launch/lockup.ts — the final frame's geometry, so
 * the app can lay the real logo and wordmark exactly where the video ends.
 */
import { Worker, isMainThread, parentPort, workerData } from 'node:worker_threads'
import { mkdirSync, readFileSync, writeFileSync, rmSync, existsSync } from 'node:fs'
import { execFileSync } from 'node:child_process'
import { cpus, tmpdir } from 'node:os'
import { join } from 'node:path'
import sharp from 'sharp'

const FPS = 60
const OUT = 'src/assets/video/launch-intro.mp4'
const LOCKUP = 'src/components/launch/lockup.ts'

async function loadAssets() {
  const { splitIcon, LAYERS } = await import('./layers.mjs')
  const { buildHandwriting } = await import('./handwriting.mjs')
  const { layers } = await splitIcon()
  const uris = {}
  for (const l of LAYERS) {
    const png = await sharp(layers[l], { raw: { width: 1024, height: 1024, channels: 4 } }).resize(720).png().toBuffer()
    uris[l] = `data:image/png;base64,${png.toString('base64')}`
  }
  const logo = await sharp('assets/images/icon.png').resize(720).png().toBuffer()
  return { layers: uris, logo: `data:image/png;base64,${logo.toString('base64')}`, hw: await buildHandwriting() }
}

if (!isMainThread) {
  const { frameSvg } = await import('./scene.mjs')
  const { assets, frames, dir, scale } = workerData
  for (const f of frames) {
    const svg = frameSvg(f / FPS, assets)
    let img = sharp(Buffer.from(svg), { density: 72 * scale })
    await img.flatten({ background: '#ffffff' }).png({ compressionLevel: 1 }).toFile(join(dir, `f${String(f).padStart(4, '0')}.png`))
    parentPort.postMessage(1)
  }
  process.exit(0)
}

const args = process.argv.slice(2)
const flag = (name) => {
  const i = args.indexOf(name)
  return i >= 0 ? args[i + 1] : undefined
}
const scene = await import('./scene.mjs')
const assets = await loadAssets()

function writeLockup() {
  const { s, tx, ty } = scene.wordLayout(assets.hw)
  const src = `/*
 * GENERATED by scripts/launch/render.mjs — don't edit by hand.
 * The intro video's last frame, as geometry: where the logo and the written
 * "Chinese Easy" sit in its ${scene.W}×${scene.H} composition, so the app can draw
 * the real thing exactly over it and take over seamlessly.
 */
export const LOCKUP = {
  composition: { width: ${scene.W}, height: ${scene.H} },
  durationMs: ${Math.round(scene.DURATION * 1000)},
  logo: { x: ${scene.LOGO_RECT.x}, y: ${scene.LOGO_RECT.y}, size: ${scene.LOGO_RECT.size} },
  word: { x: ${tx.toFixed(3)}, y: ${ty.toFixed(3)}, scale: ${s.toFixed(6)}, color: '${scene.INK}' },
  /** The word's own extent, in its units (baseline at y = 0). */
  wordBox: { width: ${assets.hw.width.toFixed(2)}, top: ${assets.hw.top.toFixed(2)}, bottom: ${assets.hw.bottom.toFixed(2)} },
} as const

/** "Chinese Easy" in Caveat Bold, one outline per letter, in the word's own units. */
export const WORD_PATHS: string[] = ${JSON.stringify(assets.hw.letters.filter((l) => l.d).map((l) => l.d))}
`
  writeFileSync(LOCKUP, src)
}

if (args.includes('--lockup-only')) {
  writeLockup()
  console.log(`wrote ${LOCKUP}`)
  process.exit(0)
}

const sheet = flag('--sheet')
if (sheet) {
  const times = sheet.split(',').map(Number)
  const out = flag('--out') ?? '.'
  const cell = 300
  const cellH = Math.round((cell * scene.H) / scene.W)
  const tiles = []
  for (const t of times) {
    const png = await sharp(Buffer.from(scene.frameSvg(t, assets))).flatten({ background: '#fff' }).resize(cell).png().toBuffer()
    const label = Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="${cell}" height="30"><text x="8" y="22" font-size="20" font-family="sans-serif" fill="#c00">${t.toFixed(2)}s</text></svg>`)
    tiles.push(await sharp(png).composite([{ input: label, top: 0, left: 0 }]).png().toBuffer())
  }
  const cols = Math.min(times.length, 6)
  const rows = Math.ceil(times.length / cols)
  await sharp({ create: { width: cols * cell, height: rows * cellH, channels: 3, background: '#888' } })
    .composite(tiles.map((input, i) => ({ input, left: (i % cols) * cell, top: Math.floor(i / cols) * cellH })))
    .png()
    .toFile(join(out, 'sheet.png'))
  console.log(`sheet: ${times.length} frames → ${join(out, 'sheet.png')}`)
  process.exit(0)
}

// Full render.
const total = Math.round(scene.DURATION * FPS) + 1
const dir = flag('--frames') ?? join(tmpdir(), 'launch-intro-frames')
if (existsSync(dir)) rmSync(dir, { recursive: true })
mkdirSync(dir, { recursive: true })
const nWorkers = Math.max(1, Math.min(cpus().length - 1, 8))
let done = 0
const started = Date.now()
await Promise.all(
  Array.from({ length: nWorkers }, (_, w) => {
    const frames = []
    for (let f = w; f < total; f += nWorkers) frames.push(f)
    return new Promise((resolve, reject) => {
      const worker = new Worker(new URL(import.meta.url), { workerData: { assets, frames, dir, scale: 1 } })
      worker.on('message', () => {
        done++
        if (done % 30 === 0) console.log(`${done}/${total} frames, ${((Date.now() - started) / 1000).toFixed(0)}s`)
      })
      worker.on('error', reject)
      worker.on('exit', (code) => (code ? reject(new Error(`worker exit ${code}`)) : resolve()))
    })
  }),
)
mkdirSync('src/assets/video', { recursive: true })
execFileSync('ffmpeg', [
  '-y', '-loglevel', 'error',
  '-framerate', String(FPS), '-i', join(dir, 'f%04d.png'),
  '-c:v', 'libx264', '-preset', 'slow', '-crf', '17', '-tune', 'animation',
  '-pix_fmt', 'yuv420p', '-profile:v', 'high', '-level', '4.2',
  '-color_primaries', 'bt709', '-color_trc', 'bt709', '-colorspace', 'bt709',
  '-movflags', '+faststart', '-an', OUT,
], { stdio: 'inherit' })
writeLockup()
console.log(`wrote ${OUT} (${(readFileSync(OUT).length / 1024).toFixed(0)} KB) and ${LOCKUP} in ${((Date.now() - started) / 1000).toFixed(0)}s`)
